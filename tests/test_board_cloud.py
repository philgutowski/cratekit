def test_issues_are_read_over_rest_when_graphql_is_refused(board, monkeypatch):
    issues = [_issue(n, f"U{n}: unit {n}", state="closed" if n % 2 else "open") for n in range(1, 251)]
    issues.append({"number": 999, "title": "a pull request", "state": "open", "body": "",
                   "labels": [], "pull_request": {"url": "x"}})
    fake = _wire(board, monkeypatch, issues)
    read = board.load_issues()
    assert [i["number"] for i in read] == list(range(1, 251)), "pull requests are not issues"
    assert {i["state"] for i in read} == {"OPEN", "CLOSED"}, "the graph reads the GraphQL spelling"
    pages = [a[1] for a in fake.calls if a[0] == "api" and "/issues?" in a[1]]
    assert len(pages) == 3, "two full pages and the short one that ends the read"


def test_the_rest_read_is_refused_past_the_limit(board, monkeypatch):
    _wire(board, monkeypatch, [_issue(n, f"U{n}: unit {n}") for n in range(1, 402)])
    monkeypatch.setattr(board, "READ_LIMIT", 300)

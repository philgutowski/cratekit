def _comments(spec: str, stale: float) -> list[dict]:
    found = []
    for part in filter(None, spec.split("; ")):
        text, _, hours = part.rpartition("@")
        ago = stale + float(hours[2:] or 0) if hours.startswith("s") else float(hours)
        found.append(_theirs(text[1:], ago) if text.startswith("!") else _mine(text, ago))
    return found


@pytest.mark.parametrize(("state", "comments"), STATES)
def test_a_cards_comments_give_its_state(board, state, comments):
    node = board.build_graph([issue(1, "U1: a")])[1]
    assert board.cloud_state(node, _comments(comments, board.STALE_HOURS))[0] == state



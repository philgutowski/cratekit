"""`scripts/board.py cloud`, the cloud lane's queue, read from the cards' comments.

A Claude Code cloud session sits behind a proxy that refuses every GraphQL call,
so `gh issue list`, `gh repo view` and `gh project` all fail there by name, and
`gh api --paginate` fails on its second page because GitHub's `Link` header
names the repository by number, a path the proxy also refuses. The script reads
the issues over REST a numbered page at a time when GraphQL is refused, and the
cloud queue reads each card's comments the same way.

The cloud session writes no label and no status, so its hold on a card is its
own last comment, told from the person's by the footer the harness appends.
The states here are the whole protocol the cloud skill follows, and the double
is a `gh` that refuses GraphQL the way the proxy does and serves REST pages the
way GitHub does.
"""

from __future__ import annotations

import importlib.util
import json
from datetime import datetime, timedelta, timezone
from pathlib import Path

import pytest

BOARD = Path(__file__).resolve().parent.parent / "scripts" / "board.py"
LANE = "cloud"
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"


@pytest.fixture
def board():
    spec = importlib.util.spec_from_file_location("board_cloud_under_test", BOARD)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _issue(number, title, *, labels=(LANE, "unit"), body="**Depends on:** none", state="open"):
    return {
        "number": number,
        "title": title,
        "state": state,
        "body": body,
        "labels": [{"name": name} for name in labels],
    }


def _stamp(hours_ago: float) -> str:
    return (datetime.now(timezone.utc) - timedelta(hours=hours_ago)).strftime("%Y-%m-%dT%H:%M:%SZ")


def _mine(heading: str, hours_ago: float, body: str = "") -> dict:
    return {"body": f"## {heading}\n\n{body}{FOOTER}", "created_at": _stamp(hours_ago)}


def _theirs(text: str, hours_ago: float) -> dict:
    return {"body": text, "created_at": _stamp(hours_ago)}


def _fake_gh(issues: list[dict], comments: dict[int, list[dict]] | None = None):
    """A `gh` that refuses GraphQL and pages REST at a hundred rows a page."""
    comments = comments or {}
    calls: list[tuple[str, ...]] = []

    def fake(*args, parse=False):
        calls.append(args)
        if args[:2] == ("api", "graphql") or args[0] in ("issue", "repo", "project"):
            raise fake.module.Fail("GitHub GraphQL is not available from Claude Code sessions")
        assert args[0] == "api", args
        path = args[1]
        assert "--paginate" not in args, "the proxy refuses the Link header's numeric paths"
        query = dict(part.split("=", 1) for part in path.split("?", 1)[1].split("&"))
        page = int(query["page"])
        per_page = int(query["per_page"])
        if "/comments" in path:
            number = int(path.split("/issues/")[1].split("/")[0])
            rows = comments.get(number, [])
        else:
            rows = issues
        batch = rows[(page - 1) * per_page : page * per_page]
        return batch if parse else json.dumps(batch)

    fake.calls = calls
    return fake


def _wire(board, monkeypatch, issues, comments=None):
    fake = _fake_gh(issues, comments)
    fake.module = board
    monkeypatch.setattr(board, "gh", fake)
    monkeypatch.setattr(board, "remote_slug", lambda: ("owner", "repo"))
    return fake


# ── the REST fallback ────────────────────────────────────────────────────────


def test_issues_are_read_over_rest_when_graphql_is_refused(board, monkeypatch):
    issues = [_issue(n, f"U{n}: unit {n}", state="closed" if n % 2 else "open") for n in range(1, 251)]
    issues.append({"number": 999, "title": "a pull request", "state": "open", "body": "",
                   "labels": [], "pull_request": {"url": "x"}})
    fake = _wire(board, monkeypatch, issues)
    read = board.load_issues()
    assert [i["number"] for i in read] == list(range(1, 251)), "pull requests are not issues"
    assert {i["state"] for i in read} == {"OPEN", "CLOSED"}, "the graph reads the GraphQL spelling"
    pages = [a[1] for a in fake.calls if a[0] == "api" and "/issues?" in a[1]]
    assert len(pages) == 3, "two full pages and the short one that ends the read"


def test_the_rest_read_is_refused_past_the_limit(board, monkeypatch):
    _wire(board, monkeypatch, [_issue(n, f"U{n}: unit {n}") for n in range(1, 402)])
    monkeypatch.setattr(board, "READ_LIMIT", 300)
    with pytest.raises(board.Truncated):
        board.load_issues()


def test_the_slug_is_read_from_the_remote_when_gh_cannot_say(board, monkeypatch):
    class Done:
        stdout = "https://github.com/some-owner/Some-Repo.git\n"

    monkeypatch.setattr(board.subprocess, "run", lambda *a, **k: Done())
    assert board.remote_slug() == ("some-owner", "Some-Repo")


# ── the states ───────────────────────────────────────────────────────────────


def _node(board, issue, *more):
    return board.build_graph([issue, *more])[issue["number"]]


def test_a_card_nobody_commented_on_is_ready(board):
    assert board.cloud_state(_node(board, _issue(1, "U1: a")), [])[0] == "ready"


def test_a_started_card_is_underway_and_stale_after_the_window(board):
    node = _node(board, _issue(1, "U1: a"))
    assert board.cloud_state(node, [_mine("Started", 1)])[0] == "underway"
    state, why = board.cloud_state(node, [_mine("Started", board.STALE_HOURS + 1)])
    assert state == "underway" and "STALE" in why


def test_a_plan_under_a_hold_is_not_a_hold_of_its_own(board):
    node = _node(board, _issue(1, "U1: a"))
    assert board.cloud_state(node, [_mine("Started", 2), _mine("Plan", 1)])[0] == "underway"


def test_a_ready_card_waits_for_the_watcher_until_a_review_arrives(board):
    node = _node(board, _issue(1, "U1: a"))
    ready = [_mine("Started", 3), _mine("Ready for the watcher", 2)]
    assert board.cloud_state(node, ready)[0] == "with-watcher"
    reviewed = ready + [_theirs("## Review from the watcher\n\nfix x", 1)]
    assert board.cloud_state(node, reviewed)[0] == "review-owed"
    addressed = reviewed + [_mine("Review addressed", 0.5)]
    assert board.cloud_state(node, addressed)[0] == "with-watcher"
    landed = addressed + [_theirs("Landed on main as abc", 0.2)]
    assert board.cloud_state(node, landed)[0] == "with-watcher", "a note is not a review"


def test_a_brainstorm_waits_for_phillip_and_his_reply_releases_it(board):
    node = _node(board, _issue(1, "U1: a"))
    asked = [_mine("Brainstorm", 2, "which of A or B?")]
    assert board.cloud_state(node, asked)[0] == "waiting-on-phillip"
    assert board.cloud_state(node, asked + [_theirs("B, please", 1)])[0] == "answered"
    question = [_mine("Question for Phillip", 2)]
    assert board.cloud_state(node, question)[0] == "waiting-on-phillip"


def test_a_card_that_needs_the_machine_is_set_aside_for_good(board):
    node = _node(board, _issue(1, "U1: a"))
    aside = [_mine("Needs the machine", 3), _theirs("ok", 1)]
    assert board.cloud_state(node, aside)[0] == "set-aside"


def test_blocked_and_attended_cards_are_never_the_clouds(board):
    dep = _issue(2, "U2: dep")
    blocked = _node(board, _issue(1, "U1: a", body="**Depends on:** #2 (U2)"), dep)
    assert board.cloud_state(blocked, [])[0] == "blocked"
    attended = _node(board, _issue(3, "U3: live", labels=(LANE, "unit", "attended")))
    assert board.cloud_state(attended, [])[0] == "attended"


def test_headings_are_read_through_markdown_and_emphasis(board):
    assert board.comment_heading("## Ready for the watcher\n\nx") == "ready for the watcher"
    assert board.comment_heading("**Started**, 2026-10-13.") == "started"
    assert board.comment_heading("\n\nReview from the watcher: the table\n") == "review from the watcher"
    assert board.comment_heading("") == ""


# ── the queue ────────────────────────────────────────────────────────────────


def test_cloud_offers_review_owed_before_answered_before_fresh(board, monkeypatch, capsys):
    issues = [
        _issue(1, "U1: fresh"),
        _issue(2, "U2: answered"),
        _issue(3, "U3: reviewed"),
        _issue(4, "U4: held"),
        _issue(5, "U5: not the cloud's", labels=("unit",)),
    ]
    comments = {
        2: [_mine("Brainstorm", 3), _theirs("go with A", 2)],
        3: [_mine("Started", 5), _mine("Ready for the watcher", 4), _theirs("## Review from the watcher", 1)],
        4: [_mine("Started", 1)],
    }
    _wire(board, monkeypatch, issues, comments)
    assert board.cmd_cloud(None) == 0
    out = capsys.readouterr().out
    assert "Take #3 (review-owed)" in out
    assert out.index("#3 ") < out.index("#2 ") < out.index("#1 ")
    assert "#4    underway" in out
    assert "#5" not in out, "a card without the label is never listed"
    assert "cloud/3-reviewed" in out


def test_cloud_says_so_when_every_card_is_held(board, monkeypatch, capsys):
    _wire(board, monkeypatch, [_issue(1, "U1: a")], {1: [_mine("Started", 1)]})
    assert board.cmd_cloud(None) == 0
    assert "Nothing for the cloud to take" in capsys.readouterr().out


def test_cloud_says_so_when_no_card_carries_the_label(board, monkeypatch, capsys):
    _wire(board, monkeypatch, [_issue(1, "U1: a", labels=("unit",))])
    assert board.cmd_cloud(None) == 0
    assert "No open card carries" in capsys.readouterr().out

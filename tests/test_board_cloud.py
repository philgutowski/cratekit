@pytest.mark.parametrize(
    ("text", "heading"),
    [
        ("## Needs the machine\n\nx", "needs the machine"),
        ("**Started**, 2026-10-13.", "started"),
        ("Started, 2026-10-13.", "started"),
        ("\n\nLanded: 5c8b26a\n", "landed"),
        ("", ""),
        (_CARD_489 + "\n\n1. Which?", "brainstorm"),
        ("Needs the machine. The card needs rekordbox", "needs the machine"),
        ("Question for Phillip? Which one", "question for phillip"),
        ("Landed; merge 5c8b26a", "landed"),
        ("**Brainstorm, round 2.**", "brainstorm"),
        # Emphasis left behind a stop, with no span to take, needs a second pass.
        ("Brainstorm**.", "brainstorm"),
        ("Landed_!", "landed"),
        # A span closed by punctuation with no space after it is still the heading.
        ("**Brainstorm**.One question waits", "brainstorm"),
        ("**Question for Phillip**?Which", "question for phillip"),
        ("Landed on main as abc", "landed on main as abc"),
        ("\n***\n\nStarted\n", "started"),
        ("Landed v0.6.0 today", "landed v0.6.0 today"),
    ],
)
def test_headings_are_read_through_markdown_emphasis_and_punctuation(board, text, heading):
    assert board.comment_heading(text) == heading


def test_a_known_heading_reads_through_trailing_punctuation_and_emphasis(board):
    # Every heading the reader knows, read off the module, so a new one is in.
    known = [value for name, value in vars(board).items() if name.startswith("HEAD_")]
    assert len(known) >= 10 and all(isinstance(v, str) and v for v in known)
    for words in known:
        t = words[:1].upper() + words[1:]
        for spelling in (
            f"{t}.", f"{t}?", f"{t}!", f"{t};", f"{t}...", f"{t}…", f"**{t}.**", f"**{t}**.",
            f"*{t}.*", f"__{t}.__", f"_{t}_!", f"## {t}.", f"## {t}?", f"### **{t}.**",
            f"**{t}?!**", f"**_{t}._**", f"{t}.**", f"**{t}.** And then a sentence, with a comma.",
            f"{t}. And then a sentence", f"{t}! Then more", f"**{t}**, then more.",
        ):
            assert board.comment_heading(f"{spelling}\n\nbody") == words, spelling


def test_cloud_offers_answered_before_resumable_before_fresh(board, monkeypatch, capsys):
    issues = [
        issue(1, "U1: fresh"),
        issue(2, "U2: answered"),
        issue(3, "U3: stale", labels=(RESIDUAL,)),
        issue(4, "U4: aside"),
        issue(5, "U5: live", labels=("unit", "attended")),
        issue(6, "a note", labels=("question",)),
    ]
    comments = {
        2: [_mine("## Brainstorm", 3), _theirs("go with A", 2)],
        3: [_mine("## Started", board.STALE_HOURS + 2)],
        4: [_mine("## Needs the machine", 1)],
    }
    _wire(board, monkeypatch, issues, comments)
    assert board.cmd_cloud(None) == 0
    out = capsys.readouterr().out
    assert "Take #2 (answered)" in out
    assert out.index("#2 ") < out.index("#3 ") < out.index("#1 ")
    assert "#4    set-aside" in out
    assert "#5    attended" in out
    assert "#6" not in out, "a card that is neither a unit nor a residual is never listed"
    assert "cloud/2-answered" in out


def _held(hours: dict) -> dict:
    return {n: [_mine("## Started", h)] for n, h in hours.items()}


@pytest.mark.parametrize(
    ("lanes", "count", "comments", "code", "said", "unsaid"),
    [
        (1, 2, _held({1: 1}), 0, ["Every lane is held"], ["Take #"]),
        (3, 5, _held({1: 2, 2: 1}), 0, ["Held, 2 of 3 lane(s): #1, #2", "Take #3 (ready)"], []),
        (None, 12, _held({n: n / 10 for n in range(1, 10)}), 0,
         ["Held, 9 of 10 lane(s): ", "Take #10 (ready)"], []),
        (None, 12, _held({n: n / 10 for n in range(1, 11)}), 0,
         ["Held, 10 of 10 lane(s): ", "Every lane is held"], ["Take #"]),
        # More holds than lanes: the earliest keep theirs and nothing is offered.
        (1, 3, _held({1: 0.5, 2: 1}), 1, ["#2, #1", "#2 held first and keep its lane"],
         ["Take #"]),
        (3, 5, _held({1: 4, 2: 3, 3: 1, 4: 2}), 1,
         ["#1, #2, #4 held first and keep their lanes"], []),
        (None, 1, {1: [_mine("## Brainstorm", 1)]}, 0, ["Nothing for the cloud to take"], []),
        (None, 0, {}, 0, ["No open unit or residual card"], []),
    ],
)
def test_the_lanes_bound_what_is_offered(
    board, monkeypatch, capsys, lanes, count, comments, code, said, unsaid
):
    issues = _cards(count) or [issue(1, "U1: a", state="closed")]
    _wire(board, monkeypatch, issues, comments)
    assert board.cmd_cloud(SimpleNamespace(lanes=lanes)) == code
    out = capsys.readouterr().out
    assert all(line in out for line in said), out
    assert not any(line in out for line in unsaid), out


def test_the_cloud_runs_ten_lanes_and_its_help_says_so(board, monkeypatch, capsys):
    assert board.CLOUD_LANES == 10, "Phillip's cap of 2026-11-21 (U291), raised from five"

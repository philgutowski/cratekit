def test_cloud_offers_answered_before_resumable_before_fresh(board, monkeypatch, capsys):
    issues = [
        _issue(1, "U1: fresh"),
        _issue(2, "U2: answered"),
        _issue(3, "U3: stale", labels=("residual",)),
        _issue(4, "U4: aside"),
        _issue(5, "U5: live", labels=("unit", "attended")),
        _issue(6, "a note", labels=("question",)),
    ]
    comments = {
        2: [_mine("Brainstorm", 3), _theirs("go with A", 2)],
        3: [_mine("Started", board.STALE_HOURS + 2)],
        4: [_mine("Needs the machine", 1)],
    }
    _wire(board, monkeypatch, issues, comments)
    assert board.cmd_cloud(None) == 0
    out = capsys.readouterr().out
    assert "Take #2 (answered)" in out
    assert out.index("#2 ") < out.index("#3 ") < out.index("#1 ")
    assert "#4    set-aside" in out
    assert "#5    attended" in out
    assert "#6" not in out, "a card that is neither a unit nor a residual is never listed"
    assert "cloud/2-answered" in out



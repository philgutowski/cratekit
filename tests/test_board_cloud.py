"""`scripts/board.py cloud`, the cloud lane's queue, read from the cards' comments.

A Claude Code cloud session sits behind a proxy that refuses every GraphQL call,
so `gh issue list`, `gh repo view` and `gh project` all fail there by name, and
`gh api --paginate` fails on its second page because GitHub's `Link` header
names the repository by number, a path the proxy also refuses. The script reads
the issues over REST a numbered page at a time when GraphQL is refused, and the
cloud queue reads each card's comments the same way.

The cloud session writes no label and no status, so its hold on a card is its
own last comment, told from the person's by the footer the harness appends.
The states here are the whole protocol the cloud skill follows: one builder at
a time, a stale hold resumed rather than abandoned, a brainstorm released by
the person's reply. The double is a `gh` that refuses GraphQL the way the
proxy does and serves REST pages the way GitHub does.
"""

from __future__ import annotations

